// ---------- Helpers for repositories ----------

export function getProfileById(id: string): Profile | undefined {
  return profiles.find((p) => p.id === id);
}

export function getDepartmentById(id: string): Department | undefined {
  return departments.find((d) => d.id === id);
}

export function getTaskById(id: string): Task | undefined {
  return tasks.find((t) => t.id === id);
}

export function getFileById(id: string): FileRecord | undefined {
  return files.find((f) => f.id === id);
}

export function getMembersByDepartment(departmentId: string): Profile[] {
  return profiles.filter((p) => p.departmentId === departmentId);
}

export function getTasksByDepartment(departmentId: string): Task[] {
  return tasks.filter((t) => t.departmentId === departmentId);
}

export function getTasksForUser(userId: string): Task[] {
  return tasks.filter(
    (t) =>
      t.creatorId === userId ||
      t.leaderId === userId ||
      t.assignees.some((a) => a.profileId === userId)
  );
}

export function getNotificationsForUser(userId: string): Notification[] {
  return notifications.filter((n) => n.recipientId === userId);
}

export function getUnreadNotificationCount(userId: string): number {
  return notifications.filter((n) => n.recipientId === userId && !n.isRead).length;
}

